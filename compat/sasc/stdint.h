/* The exact-width types Wipeout's headers use, for SAS/C, whose C library
   predates <stdint.h>. */

#ifndef BENCHWORK_COMPAT_STDINT_H
#define BENCHWORK_COMPAT_STDINT_H

typedef signed char int8_t;
typedef unsigned char uint8_t;
typedef short int16_t;
typedef unsigned short uint16_t;
typedef int int32_t;
typedef unsigned int uint32_t;

#endif
