// Host-side generator for src/glyphs.c: loads a TrueType font with the
// system FreeType, takes the outlines of the printable ASCII glyphs at a
// fixed pixel size, unhinted, and writes them out as C tables in 26.6 fixed
// point. The Amiga benchmark then feeds those outlines to ftgrays.c without
// needing a font loader.
//
//   cc $(pkg-config --cflags --libs freetype2) -o dumpglyphs dumpglyphs.c
//   ./dumpglyphs /usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf > ../src/glyphs.c

#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_OUTLINE_H
#include <stdio.h>
#include <stdlib.h>

#define PIXELS 32
#define FIRST 33
#define LAST 126

int main(int argc, char **argv) {
    FT_Library lib;
    FT_Face face;
    int npoints = 0, ncontours = 0;

    if (argc != 2) {
        fprintf(stderr, "usage: dumpglyphs <font.ttf>\n");
        return 1;
    }
    if (FT_Init_FreeType(&lib) || FT_New_Face(lib, argv[1], 0, &face) ||
        FT_Set_Pixel_Sizes(face, 0, PIXELS)) {
        fprintf(stderr, "cannot load %s\n", argv[1]);
        return 1;
    }

    printf("// Generated by tools/dumpglyphs.c from %s at %d px: do not edit.\n",
           face->family_name, PIXELS);
    printf("//\n// Outlines of ASCII %d to %d in 26.6 fixed point, unhinted.\n",
           FIRST, LAST);
    printf("// Each glyph is a run of points and a run of contour end indices;\n");
    printf("// the tags are FreeType's: bit 0 set for an on-curve point, bit 1\n");
    printf("// set for a cubic control point, neither for a conic control.\n\n");
    printf("#include \"glyphs.h\"\n\n");

    printf("const short GLYPH_POINTS[][2] = {\n");
    for (int c = FIRST; c <= LAST; c++) {
        FT_Outline *o;

        if (FT_Load_Char(face, (FT_ULong)c, FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP))
            continue;
        o = &face->glyph->outline;
        printf("    // '%c'\n", c);
        for (int i = 0; i < o->n_points; i++)
            printf("    {%ld, %ld},\n", (long)o->points[i].x, (long)o->points[i].y);
    }
    printf("};\n\n");

    printf("const char GLYPH_TAGS[] = {\n");
    for (int c = FIRST; c <= LAST; c++) {
        FT_Outline *o;

        if (FT_Load_Char(face, (FT_ULong)c, FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP))
            continue;
        o = &face->glyph->outline;
        printf("   ");
        for (int i = 0; i < o->n_points; i++)
            printf(" %d,", o->tags[i] & 3);
        printf("\n");
    }
    printf("};\n\n");

    printf("const short GLYPH_CONTOURS[] = {\n");
    for (int c = FIRST; c <= LAST; c++) {
        FT_Outline *o;

        if (FT_Load_Char(face, (FT_ULong)c, FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP))
            continue;
        o = &face->glyph->outline;
        printf("   ");
        for (int i = 0; i < o->n_contours; i++)
            printf(" %d,", o->contours[i]);
        printf("\n");
    }
    printf("};\n\n");

    printf("const struct glyph GLYPHS[] = {\n");
    for (int c = FIRST; c <= LAST; c++) {
        FT_Outline *o;

        if (FT_Load_Char(face, (FT_ULong)c, FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP))
            continue;
        o = &face->glyph->outline;
        printf("    {%d, %d, %d, %d, %ld}, // '%c'\n", npoints, o->n_points,
               ncontours, o->n_contours, (long)face->glyph->advance.x, c);
        npoints += o->n_points;
        ncontours += o->n_contours;
    }
    printf("};\n\n");
    printf("const int NGLYPHS = sizeof(GLYPHS) / sizeof(GLYPHS[0]);\n");
    printf("const int GLYPH_PIXELS = %d;\n", PIXELS);
    printf("const int GLYPH_ASCENT = %ld;\n",
           (long)(face->size->metrics.ascender));
    printf("const int GLYPH_LINE_HEIGHT = %ld;\n",
           (long)(face->size->metrics.height));
    return 0;
}
